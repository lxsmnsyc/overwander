import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import * as v from 'valibot';
import { parse, stringify } from 'yaml';

/**
 * Writes the official Japanese and Spanish names of every species,
 * move, ability, item, type and nature into `src/data/text/ja/` and
 * `src/data/text/es/`, from PokeAPI's tables. Run it again after adding
 * an entry the mainline games name:
 *
 * ```bash
 * pnpm official-names
 * ```
 *
 * The script formats what it writes with oxfmt afterwards.
 *
 * An entry is matched by its English name. One the games do not name
 * (a signature ability, a Zenith, an item of this game's own) is left
 * out of the locale files and reads in English. Japanese is the kana
 * the games show by default, never kanji. The files it writes are
 * generated: edit this script or the English, not them.
 */

/** The PokeAPI commit the tables are read at, so a run is repeatable */
const POKEAPI_COMMIT = '6b8db7f3cb31cfaa37cb74e5c3edff124bcba5ce';

const TABLE_URL = `https://raw.githubusercontent.com/PokeAPI/pokeapi/${POKEAPI_COMMIT}/data/v2/csv`;

const CACHE = join('node_modules/.cache/pokeapi', POKEAPI_COMMIT);

const TEXT = 'src/data/text';

/** PokeAPI's language ids */
const ENGLISH = '9';
const JAPANESE_KANA = '1';
const JAPANESE = '11';
const SPANISH = '7';

const LOCALES = ['ja', 'es'] as const;

type Locale = (typeof LOCALES)[number];

const HEADER = '# Generated by scripts/i18n/official-names.ts from PokeAPI. Do not edit.\n';

/** One thing's official name in each locale, and a species' category */
interface Official {
  name: Partial<Record<Locale, string>>;
  category?: Partial<Record<Locale, string>>;
}

type Row = Record<string, string>;

async function readTable(table: string): Promise<Row[]> {
  // Each table is downloaded once per commit and kept beside the modules
  const path = join(CACHE, `${table}.csv`);

  if (!existsSync(path)) {
    const response = await fetch(`${TABLE_URL}/${table}.csv`);

    if (!response.ok) {
      throw new Error(`${table}.csv: ${response.status} ${response.statusText}`);
    }
    mkdirSync(CACHE, { recursive: true });
    writeFileSync(path, await response.text());
  }
  return parseCsv(readFileSync(path, 'utf8'));
}

function parseCsv(text: string): Row[] {
  // Split into records, a quoted field may hold commas, quotes and line breaks
  const records: string[][] = [];
  let record: string[] = [];
  let field = '';
  let quoted = false;

  for (let at = 0; at < text.length; at++) {
    const char = text[at];

    if (quoted) {
      if (char === '"' && text[at + 1] === '"') {
        field += '"';
        at++;
      } else if (char === '"') {
        quoted = false;
      } else {
        field += char;
      }
    } else if (char === '"') {
      quoted = true;
    } else if (char === ',') {
      record.push(field);
      field = '';
    } else if (char === '\n') {
      record.push(field.replace(/\r$/, ''));
      records.push(record);
      record = [];
      field = '';
    } else {
      field += char;
    }
  }
  if (field !== '' || record.length > 0) {
    record.push(field);
    records.push(record);
  }

  // Key each record by the header
  const [header, ...rest] = records;
  const rows: Row[] = [];

  for (const values of rest) {
    const row: Row = {};

    for (const [index, column] of header.entries()) {
      row[column] = values[index] ?? '';
    }
    rows.push(row);
  }
  return rows;
}

function splitWords(name: string): string[] {
  // Accents, punctuation and case differ between two spellings of one name,
  // and the games write Nidoran's sex as a sign where this game writes a letter
  const plain = name
    .replaceAll('♀', ' f')
    .replaceAll('♂', ' m')
    .normalize('NFKD')
    .replaceAll(/\p{M}/gu, '')
    .toLowerCase()
    .replaceAll(/['’]s\b/g, '')
    .replaceAll('-', ' ')
    .replaceAll(/[^a-z0-9 ]/g, '');
  const words: string[] = [];

  for (const word of plain.split(' ')) {
    if (word !== '') {
      words.push(word);
    }
  }
  return words;
}

function normalizeName(name: string): string {
  // Spacing differs too: "Double Edge" and "Double-Edge", "MimeJr" and "Mime Jr."
  return splitWords(name).join('');
}

/** Words a form's name carries that say only that it is a form */
const FORM_WORDS = new Set([
  'form',
  'forme',
  'pattern',
  'mode',
  'style',
  'cloak',
  'striped',
  'standard',
  'paldean',
]);

function normalizeFormName(name: string): string {
  // "Aegislash Blade" and "Blade Forme Aegislash" are one form: compare the words in any order
  const words: string[] = [];

  for (const word of splitWords(name)) {
    if (!FORM_WORDS.has(word)) {
      words.push(word);
    }
  }
  words.sort();
  return words.join('');
}

/** The names this game still spells the way an older game did, to the name PokeAPI keeps now */
const RENAMED = new Map([
  ['vicegrip', 'visegrip'],
  ['stick', 'leek'],
  ['prettywing', 'prettyfeather'],
  ['healthwing', 'healthfeather'],
  ['musclewing', 'musclefeather'],
  ['resistwing', 'resistfeather'],
  ['geniuswing', 'geniusfeather'],
  ['cleverwing', 'cleverfeather'],
  ['swiftwing', 'swiftfeather'],
]);

function findRenamed(name: string): string {
  const normalized = normalizeName(name);

  return RENAMED.get(normalized) ?? normalized;
}

/** Kanji, which the kana names never hold */
const KANJI = /\p{Script=Han}/u;

function readLocaleName(
  byLanguage: ReadonlyMap<string, string>,
  locale: Locale,
): string | undefined {
  if (locale === 'es') {
    return byLanguage.get(SPANISH);
  }

  // Japanese is the kana; the plain Japanese name stands in only where it has no kanji
  const kana = byLanguage.get(JAPANESE_KANA);

  if (kana != null) {
    return kana;
  }

  const plain = byLanguage.get(JAPANESE);

  return plain != null && !KANJI.test(plain) ? plain : undefined;
}

/** Names by English name, from a names table that lists every language of each id */
function indexNames(
  rows: Row[],
  idColumn: string,
  nameColumn: string,
  extraColumn?: string,
  normalize: (name: string) => string = normalizeName,
): Map<string, { names: Map<string, string>; extras: Map<string, string> }> {
  // Every language's name and extra for each id
  const byId = new Map<string, { names: Map<string, string>; extras: Map<string, string> }>();
  const english = new Map<string, string>();

  for (const row of rows) {
    const id = row[idColumn];
    const language = row.local_language_id;
    const name = row[nameColumn];
    let entry = byId.get(id);

    if (entry == null) {
      entry = { names: new Map(), extras: new Map() };
      byId.set(id, entry);
    }
    if (name !== '') {
      entry.names.set(language, name);
    }
    if (extraColumn != null && row[extraColumn] !== '') {
      entry.extras.set(language, row[extraColumn]);
    }
    if (language === ENGLISH && name !== '' && !english.has(normalize(name))) {
      english.set(normalize(name), id);
    }
  }

  // The same, keyed by the English name an entry is matched on
  const byEnglish = new Map<string, { names: Map<string, string>; extras: Map<string, string> }>();

  for (const [name, id] of english) {
    const entry = byId.get(id);

    if (entry != null) {
      byEnglish.set(name, entry);
    }
  }
  return byEnglish;
}

function toOfficial(
  entry: { names: Map<string, string>; extras: Map<string, string> },
  withCategory: boolean,
): Official {
  const official: Official = { name: {} };

  for (const locale of LOCALES) {
    const name = readLocaleName(entry.names, locale);

    if (name != null) {
      official.name[locale] = name;
    }
  }

  // A species' category is its genus, which the species table keeps beside the name
  if (withCategory) {
    official.category = {};
    for (const locale of LOCALES) {
      const category = readLocaleName(entry.extras, locale);

      if (category != null) {
        official.category[locale] = category;
      }
    }
  }
  return official;
}

function listYaml(folder: string): string[] {
  const found: string[] = [];

  for (const entry of readdirSync(folder, { withFileTypes: true, recursive: true })) {
    if (entry.isFile() && entry.name.endsWith('.yaml')) {
      found.push(join(entry.parentPath, entry.name));
    }
  }
  found.sort();
  return found;
}

function writeLocaleFile(
  englishPath: string,
  locale: Locale,
  content: Record<string, unknown>,
): void {
  // A locale file sits where its English file does, under its own locale's folder
  const path = join(TEXT, locale, relative(join(TEXT, 'en'), englishPath));

  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, HEADER + stringify(content, { lineWidth: 0 }));
}

interface Tally {
  matched: number;
  unmatched: string[];
}

const ENTRIES = v.record(v.string(), v.unknown());

const WORDS = v.object({ name: v.string(), category: v.optional(v.string()) });

const TABLE = v.record(v.string(), v.string());

/** One locale's fields for one entry */
type Entry = Record<string, string>;

function writeEntries(
  folder: string,
  find: (english: string) => Official | undefined,
  nested: boolean,
): Tally {
  const tally: Tally = { matched: 0, unmatched: [] };

  for (const path of listYaml(join(TEXT, 'en', folder))) {
    const english = v.parse(ENTRIES, parse(readFileSync(path, 'utf8')));

    // A species file keeps its species under their family; the rest are flat
    const groups: [string | undefined, Record<string, unknown>][] = [];

    if (nested) {
      for (const [family, members] of Object.entries(english)) {
        groups.push([family, v.parse(ENTRIES, members)]);
      }
    } else {
      groups.push([undefined, english]);
    }

    // Each locale's entries, group by group in the English order
    const written: Record<Locale, [string | undefined, Record<string, Entry>][]> = {
      ja: [],
      es: [],
    };

    for (const [family, entries] of groups) {
      const found: Record<Locale, Record<string, Entry>> = { ja: {}, es: {} };

      for (const [key, value] of Object.entries(entries)) {
        // The item templates are sentences, not names
        if (key === 'templates') {
          continue;
        }

        const words = v.parse(WORDS, value);
        const official = find(words.name);

        if (official == null) {
          tally.unmatched.push(key);
          continue;
        }
        tally.matched++;

        // Each locale writes only the fields it has an official word for
        for (const locale of LOCALES) {
          const entry: Entry = {};
          const name = official.name[locale];
          const category = official.category?.[locale];

          if (name != null) {
            entry.name = name;
          }
          if (category != null && words.category != null) {
            entry.category = category;
          }
          if (Object.keys(entry).length > 0) {
            found[locale][key] = entry;
          }
        }
      }
      for (const locale of LOCALES) {
        if (Object.keys(found[locale]).length > 0) {
          written[locale].push([family, found[locale]]);
        }
      }
    }

    // A file is written only where its locale names something in it
    for (const locale of LOCALES) {
      const content: Record<string, unknown> = {};

      for (const [family, entries] of written[locale]) {
        if (family == null) {
          Object.assign(content, entries);
        } else {
          content[family] = entries;
        }
      }
      if (Object.keys(content).length > 0) {
        writeLocaleFile(path, locale, content);
      }
    }
  }
  return tally;
}

function writeTable(file: string, find: (english: string) => Official | undefined): Tally {
  // A flat table of names keyed by enum member, such as types.yaml
  const path = join(TEXT, 'en', file);
  const english = v.parse(TABLE, parse(readFileSync(path, 'utf8')));
  const tally: Tally = { matched: 0, unmatched: [] };
  const written: Record<Locale, Record<string, string>> = { ja: {}, es: {} };

  for (const [key, name] of Object.entries(english)) {
    const official = find(name);

    if (official == null) {
      tally.unmatched.push(key);
      continue;
    }
    tally.matched++;
    for (const locale of LOCALES) {
      const translated = official.name[locale];

      if (translated != null) {
        written[locale][key] = translated;
      }
    }
  }
  for (const locale of LOCALES) {
    writeLocaleFile(path, locale, written[locale]);
  }
  return tally;
}

function report(label: string, tally: Tally): void {
  console.log(`${label}: ${tally.matched} named, ${tally.unmatched.length} left in English`);
  if (tally.unmatched.length > 0) {
    console.log(`  ${tally.unmatched.join(', ')}`);
  }
}

async function main(): Promise<void> {
  // Species match on the species name or, for a form, the form's full name
  const species = indexNames(
    await readTable('pokemon_species_names'),
    'pokemon_species_id',
    'name',
    'genus',
  );
  const forms = indexNames(
    await readTable('pokemon_form_names'),
    'pokemon_form_id',
    'pokemon_name',
    undefined,
    normalizeFormName,
  );

  report(
    'species',
    writeEntries(
      'species',
      (name) => {
        const found = species.get(normalizeName(name)) ?? forms.get(normalizeFormName(name));

        return found == null ? undefined : toOfficial(found, true);
      },
      true,
    ),
  );

  // Moves, abilities and items match on their names alone
  for (const [folder, table, idColumn] of [
    ['moves', 'move_names', 'move_id'],
    ['abilities', 'ability_names', 'ability_id'],
    ['items', 'item_names', 'item_id'],
  ] as const) {
    const index = indexNames(await readTable(table), idColumn, 'name');

    report(
      folder,
      writeEntries(
        folder,
        (name) => {
          const found = index.get(findRenamed(name));

          return found == null ? undefined : toOfficial(found, false);
        },
        false,
      ),
    );
  }

  // Types and natures are flat tables of names
  for (const [file, table, idColumn] of [
    ['types.yaml', 'type_names', 'type_id'],
    ['natures.yaml', 'nature_names', 'nature_id'],
  ] as const) {
    const index = indexNames(await readTable(table), idColumn, 'name');

    report(
      file,
      writeTable(file, (name) => {
        const found = index.get(normalizeName(name));

        return found == null ? undefined : toOfficial(found, false);
      }),
    );
  }
}

await main();
